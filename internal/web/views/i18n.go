package views

// Server-side i18n for the tabs (the SIP island keeps its own i18n.js).
// Language flows from the wp-lang cookie (written by the island's
// language switch), falling back to the Accept-Language header and
// English. SSE fragments render through the per-extension language the
// hub remembers, because the notifier renders without a request.

// Lang is a supported UI language.
type Lang string

const (
	LangEN Lang = "en"
	LangDE Lang = "de"
)

// ParseLang maps a raw value (cookie, header) onto a supported Lang,
// defaulting to English.
func ParseLang(raw string) Lang {
	switch Lang(raw) {
	case LangDE:
		return LangDE
	default:
		return LangEN
	}
}

