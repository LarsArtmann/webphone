// T looks up a UI string. Missing German entries fall back to English;
// unknown keys return the key itself so a typo is visible, not silent.
func T(lang Lang, key string) string {
	if table, ok := dictionaries[lang]; ok {
		if value, ok := table[key]; ok {
			return value
		}
	}
	if value, ok := dictionaries[LangEN][key]; ok {
		return value
	}
	return key
}
