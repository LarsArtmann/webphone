#!/usr/bin/env bash
# templ-generate.sh — regenerate the committed templ views with the RIGHT
# compiler, every time.
#
# Why this exists (the 2026-11-05 near-miss class): the codegen must match
# go.mod's templ LIBRARY exactly. Two ways to get it wrong, both of which build
# locally and red main:
#
#   * the devshell's pkgs.templ is OLDER (v0.3.1020) than the library — its
#     output still references pre-wave symbols that no longer compile;
#   * a CLI NEWER than the library emits templruntime.NewAttributeExpression,
#     which the pinned library does not have.
#
# So the version is READ FROM go.mod, never assumed, and the generated header
# stamp is verified afterwards: templ writes the compiler version into every
# *_templ.go, which makes drift detectable instead of invisible.
#
#   scripts/templ-generate.sh              regenerate ./internal/web/views/
#   scripts/templ-generate.sh --check      verify the tree is already in sync
#
# Exit 0 = generated (or already in sync); 1 = version mismatch / drift /
# generation failure; 2 = environment.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
cd "$ROOT"

MODE=generate
case "${1:-}" in
--check) MODE=check ;;
"") ;;
*)
	echo "templ-generate: unknown argument '$1' (only --check)" >&2
	exit 2
	;;
esac

command -v go >/dev/null 2>&1 || {
	echo "templ-generate: FATAL: go not on PATH — run inside nix develop" >&2
	exit 2
}

# The library version go.mod pins. One source of truth: a bump updates go.mod,
# and this script follows without a second edit.
TEMPL_VERSION=$(awk '$1 == "github.com/a-h/templ" { print $2; exit }' go.mod)
[ -n "$TEMPL_VERSION" ] || {
	echo "templ-generate: FATAL: github.com/a-h/templ not found in go.mod" >&2
	exit 2
}

echo "templ-generate: go.mod pins templ $TEMPL_VERSION"

# A CLI on PATH that disagrees is the exact trap: report it and continue with
# the PINNED one (the shell's pkgs.templ is expected to be older).
if command -v templ >/dev/null 2>&1; then
	onpath=$(templ version 2>/dev/null | awk '{ print $NF }' || true)
	if [ -n "$onpath" ] && [ "$onpath" != "$TEMPL_VERSION" ]; then
		echo "templ-generate: WARN: PATH templ is $onpath, go.mod pins $TEMPL_VERSION — using the pinned module"
	fi
fi

run_pinned() {
	go run "github.com/a-h/templ/cmd/templ@${TEMPL_VERSION}" "$@"
}

if [ "$MODE" = check ]; then
	# Snapshot the committed bytes FIRST: the generator writes in place, so a
	# plain "generate then git diff" cannot see drift — the regeneration
	# overwrites the stale file and git happily reports a clean tree (learned
	# by testing it: a planted drift came back as "in sync"). Compare against
	# the snapshot, then restore so --check never mutates the tree.
	snapshot=$(mktemp -d)
	trap 'rm -rf "$snapshot"' EXIT
	shopt -s nullglob
	generated=(internal/web/views/*_templ.go)
	shopt -u nullglob
	[ "${#generated[@]}" -gt 0 ] || {
		echo "templ-generate: FATAL: no *_templ.go under internal/web/views/" >&2
		exit 2
	}
	cp -a "${generated[@]}" "$snapshot/"

	run_pinned generate ./internal/web/views/ >/dev/null

	drift=0
	for f in "${generated[@]}"; do
		if ! cmp -s "$f" "$snapshot/$(basename "$f")"; then
			echo "STALE: $f" >&2
			drift=1
		fi
	done
	if [ "$drift" -eq 1 ]; then
		# Restore: a check must leave the tree exactly as it found it.
		cp -a "$snapshot/." internal/web/views/
		echo "templ-generate: DRIFT — the committed views were not generated by templ $TEMPL_VERSION." >&2
		echo "Run scripts/templ-generate.sh and commit the result." >&2
		exit 1
	fi
	echo "templ-generate: views are in sync with templ $TEMPL_VERSION"
	exit 0
fi

run_pinned generate ./internal/web/views/

# Verify the stamp: templ records the compiler version in the generated header.
stamp=$(grep -ho 'templ: version: v[0-9][^ ]*' internal/web/views/*_templ.go 2>/dev/null | head -1 | awk '{ print $NF }' || true)
if [ -z "$stamp" ]; then
	echo "templ-generate: WARN: no 'templ: version:' stamp found in the generated files — the header contract moved upstream" >&2
elif [ "$stamp" != "$TEMPL_VERSION" ]; then
	echo "templ-generate: FATAL: generated header says '$stamp' but go.mod pins '$TEMPL_VERSION' — a mismatched CLI just wrote code the library cannot compile" >&2
	exit 1
fi
echo "templ-generate: generated ./internal/web/views/ with templ $TEMPL_VERSION (header stamp: ${stamp:-none})"
