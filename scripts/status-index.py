#!/usr/bin/env python3
"""Regenerate docs/status/INDEX.md — one row per point-in-time status report.

Born in the 2026-11-05 hygiene train: docs/status had grown past 130 reports
with no table of contents, so "is there already a report about X?" required a
grep-per-question. The index is GENERATED, never hand-edited (a hand edit is
drift by definition); `--check` verifies the committed index still matches the
directory and exits 1 otherwise, so a CI lane can adopt it later. Content
comparison only (names + titles, not bytes) — the daemon's table reflow must
not trip the check (the treefmt-cache lesson: formatter output ACQUITS).
"""

import argparse
import json
import pathlib
import subprocess  # nosec B404 - dprint fmt runner only (the generated-index post-fmt step)
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
STATUS = ROOT / "docs" / "status"
INDEX = STATUS / "INDEX.md"


def live_report_glob() -> str:
    """The ONE report-count rule, read from the docs-gates config.

    The cadence gate, the routing gate and this index must agree about what a
    "live status report" is, so the rule is not restated here: it is
    `report_glob` in `.docs-gates.json` (default `2*.md`, matching the
    historical layout). Disagreement is how three counters read 76/75/70 in one
    afternoon (TODO §2026-11-07 r21(c)).
    """
    cfg = ROOT / ".docs-gates.json"
    try:
        return json.loads(cfg.read_text()).get("report_glob", "2*.md")
    except (OSError, ValueError):
        return "2*.md"


def live_report_count() -> int:
    return sum(1 for p in STATUS.glob(live_report_glob()) if p.name != "INDEX.md")


HEADER = "<!-- GENERATED by scripts/status-index.py — do not hand-edit; regenerate: python3 scripts/status-index.py -->"


def title_of(path: pathlib.Path) -> str:
    """First '# ' or '## ' heading, else the filename stem."""
    for line in path.read_text(errors="replace").splitlines():
        if line.startswith(("# ", "## ")):
            return line.lstrip("#").strip()
    return path.stem


def computed_rows() -> list[tuple[str, str]]:
    rows = []
    for path in list(STATUS.glob(live_report_glob())) + list(STATUS.glob("*.html")):
        if path.name == "INDEX.md":
            continue
        rows.append((path.name, title_of(path)))
    # Filenames start with ISO dates, so reverse sort = newest first.
    return sorted(rows, key=lambda r: r[0], reverse=True)


def render(rows: list[tuple[str, str]]) -> str:
    lines = [
        HEADER,
        "",
        (
            f"{live_report_count()} status reports, newest first. Historical snapshots —"
            " open items live in the living docs (TODO_LIST), never here. The count"
            " follows `report_glob` in `.docs-gates.json`, so the cadence gate and this"
            " index cannot disagree about how many live reports exist."
        ),
        "",
        "| Report | Title |",
        "| --- | --- |",
    ]
    for name, title in rows:
        safe = title.replace("|", "\\|")
        lines.append(f"| [`{name}`]({name}) | {safe} |")
    return "\n".join(lines) + "\n"


def parsed_rows(text: str) -> list[tuple[str, str]]:
    import re

    # The daemon/dprint aligns table cells with padding; match content only.
    row = re.compile(r"^\|\s*\[`(.+?)`\]\([^)]+\)\s*\|\s*(.+?)\s*\|$")
    rows = []
    for line in text.splitlines():
        m = row.match(line)
        if m:
            rows.append((m.group(1), m.group(2).replace("\\|", "|")))
    return rows


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--check", action="store_true", help="verify INDEX.md matches the directory"
    )
    args = ap.parse_args()

    rows = computed_rows()
    if args.check:
        if not INDEX.exists():
            print("docs/status/INDEX.md missing", file=sys.stderr)
            return 1
        want = {name: title for name, title in rows}
        got = {name: title for name, title in parsed_rows(INDEX.read_text())}
        missing = sorted(set(want) - set(got))
        extra = sorted(set(got) - set(want))
        drifted = sorted(n for n in set(want) & set(got) if want[n] != got[n])
        for n in missing:
            print(f"MISSING from index: {n}")
        for n in extra:
            print(f"STALE in index (file gone): {n}")
        for n in drifted:
            print(f"TITLE drifted: {n}")
        return 1 if (missing or extra or drifted) else 0

    INDEX.write_text(render(rows))
    print(f"wrote {INDEX.relative_to(ROOT)} ({len(rows)} reports)")
    _format_with_dprint()
    return 0


def _format_with_dprint() -> None:
    """Leave the tree CANONICAL, not just written.

    dprint owns table-cell alignment in this repo, so a freshly rendered index
    is unformatted by construction: the next `dprint check` would red on a file
    nobody edited. Formatting here keeps "regenerate the index" a single
    command. Best-effort by design, a missing dprint must not fail the regen.
    """
    try:
        subprocess.run(  # nosec B603,B607 - pinned "dprint" dev tool resolved from PATH, argv-list, never shell
            ["dprint", "fmt", str(INDEX.relative_to(ROOT))],
            cwd=ROOT,
            check=True,
            capture_output=True,
        )
    except (OSError, subprocess.CalledProcessError):
        print(
            "note: dprint not available/failed — run `dprint fmt` before the gates",
            file=sys.stderr,
        )


if __name__ == "__main__":
    sys.exit(main())
